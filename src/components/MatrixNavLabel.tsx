const pixel = (x: number, y: number) => `M${x} ${y}h.72v.72h-.72Z`;
const paths = Object.fromEntries(
  Object.entries(glyphs).map(([letter, rows]) => {
    let path = rows
      .flatMap((row, y) => Array.from(row, (bit, x) => (bit === '1' ? pixel(x, y) : '')))
      .join('');
    if (letter === 'Ё') path += pixel(1, -2) + pixel(3, -2);
    if (letter === 'Й') path += pixel(1, -2) + pixel(2, -1) + pixel(3, -2);
    return [letter, path];
  }),
);

/** The text stays accessible; a reserved SVG layer replaces it on hover/focus. */
export function MatrixNavLabel({ text }: { text: string }) {
  const letters = Array.from(text.toUpperCase());
  if (!letters.length || letters.some((letter) => !Object.hasOwn(paths, letter))) {
    return <span>{text}</span>;
  }
  const columns = letters.length * 6 - 1;
  return (
    <span
      className="nav-label"
      style={
        {
          '--matrix-steps': letters.length,
          '--matrix-duration': `${letters.length * 30}ms`,
        } as CSSProperties
      }
    >
      <span className="nav-label-text">{text}</span>
      <span className="nav-matrix" aria-hidden="true" key={text}>
        <svg
          viewBox={`0 -2 ${columns} 9`}
          width={columns * 1.5}
          height="13.5"
          focusable="false"
          fill="currentColor"
          shapeRendering="crispEdges"
        >
          {letters.map((letter, index) => (
            <path key={index} d={paths[letter]} transform={`translate(${index * 6} 0)`} />
          ))}
        </svg>
      </span>
    </span>
  );
}
